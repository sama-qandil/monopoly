    public function LinkAccount(LinkAccountRequest $request)
    {
        $user = $request->user();
        if ($user->email) {
            return $this->error('Account already linked to an email', 400);
        }

        $validateduser = $request->validated();

        $user->update([
            'email' => $validateduser['email'],
            'password' => Hash::make($validateduser['password']),
            'provider_id' => $validateduser['provider_id'] ?? $user->provider_id,
        ]);


        $otp = rand(100000, 999999);

    // بنخزن البيانات اللي اللاعب عايز يربطها مؤقتاً في الكاش مع الكود
