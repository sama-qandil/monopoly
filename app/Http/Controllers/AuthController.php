    return $this->success(null, 'OTP sent to verify your new email.');

        // return $this->success(['user' => new UserResource($user)], 'Account linked successfully');
    }










public function verifyOtp(Request $request)
{
    $request->validate([
        'email' => 'required|email',
        'otp' => 'required|numeric',
        'type' => 'required|in:register,link' // عشان نعرف إحنا بنتحقق من إيه
    ]);

    $cachedOtp = Cache::get('otp_' . $request->email);

    if ($request->type == 'register') {
        if ($cachedOtp && $cachedOtp == $request->otp) {
            $user = User::where('email', $request->email)->first();
            $token = $user->createToken('user_token')->plainTextToken;
            Cache::forget('otp_' . $request->email); // مسح الكود بعد الاستخدام

            return $this->success(['user' => new UserResource($user), 'token' => $token], 'Verified successfully');
        }
    } 
    
    if ($request->type == 'link') {
        if (!$request->user()) {
        return $this->error('Unauthorized', 401);
    }
        $linkData = Cache::get('link_data_' . $request->user()->id);
        
        if ($linkData && $linkData['otp'] == $request->otp && $linkData['email'] == $request->email) {
            $request->user()->update([
                'email' => $linkData['email'],
                'password' => Hash::make($linkData['password']),
            ]);
            Cache::forget('link_data_' . $request->user()->id);

            return $this->success(['user' => new UserResource($request->user())], 'Account linked successfully');
        }
    }

    return $this->error('Invalid or expired OTP', 422);
}
















    public function login(LoginRequest $request)
    {
        $validated = $request->validated();

        $user = User::where('email', $validated['email'])->first();
        if (! $user || ! Hash::check($validated['password'], $user->password)) {
            return $this->error('Invalid credentials', 401);
        }

        $token = $user->createToken('user_token')->plainTextToken;

        return $this->success([
            'user' => new UserResource($user),
            'token' => $token,
        ], 'Logged in successfully');
    }

    public function logout(Request $request)
    {
        $request->user()->tokens()->delete();

        return $this->success(null, 'Logged out successfully');
    }

    public function handleProviderCallback($provider)
    {
        $socialUser = Socialite::driver($provider)->user();
        $user = User::firstOrCreate(
            ['email' => $socialUser->getEmail()],
            [
                'username' => $socialUser->getName(),
                'provider_id' => $socialUser->getId(),
                'provider_name' => $provider,
                'avatar' => $socialUser->getAvatar(),

            ]
        );

        $token = $user->createToken('auth_token')->plainTextToken;

        return $this->success(['token' => $token, 'user'    => new UserResource($user),]);
      
    }
}
